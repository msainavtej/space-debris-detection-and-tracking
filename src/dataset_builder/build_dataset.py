import os
import csv
import random
import shutil
import cv2

# =========================
# Configuration
# =========================
INPUT_ROOT = "data/raw/synthetic_videos"
OUTPUT_ROOT = "data/processed/yolo_dataset"

IMG_SIZE = 640
SPLIT_RATIOS = {"train": 0.70, "val": 0.20, "test": 0.10}


# =========================
# Step 1: Sequence-Level Split
# =========================
def get_video_splits():
    # Gather all sequence folder names
    all_sequences = [d for d in os.listdir(INPUT_ROOT) if os.path.isdir(os.path.join(INPUT_ROOT, d))]
    
    random.seed(42)  # Maintain deterministic splits
    random.shuffle(all_sequences)

    total_videos = len(all_sequences)
    train_count = int(total_videos * SPLIT_RATIOS["train"])
    val_count = train_count + int(total_videos * SPLIT_RATIOS["val"])

    video_splits = {
        "train": all_sequences[:train_count],
        "val": all_sequences[train_count:val_count],
        "test": all_sequences[val_count:]
    }
    
    print("\n🔍 Debug Verification - Split Array Breakdown:")
    for split_type, items in video_splits.items():
        print(f" ├─ {split_type.capitalize()} (Count: {len(items)}): {items[:3]}... {items[-1:] if items else ''}")
        
    return video_splits


# =========================
# Step 2: Extract & Direct Sort
# =========================
def process_and_build(video_splits):
    print("\n🎬 Processing video frame streams and applying direct label normalization...")

    for split_name, sequences in video_splits.items():
        for seq in sequences:
            seq_path = os.path.join(INPUT_ROOT, seq)
            video_path = os.path.join(seq_path, f"{seq}.mp4")
            csv_path = os.path.join(seq_path, f"{seq}_ground_truth.csv")

            if not os.path.exists(video_path) or not os.path.exists(csv_path):
                continue

            # Load the ground truth rows relative to this video's frames
            frame_annotations = {}
            with open(csv_path, mode='r') as f:
                reader = csv.DictReader(f)
                for row in reader:
                    f_idx = int(row['frame'])
                    if f_idx not in frame_annotations:
                        frame_annotations[f_idx] = []
                    frame_annotations[f_idx].append(row)

            # Stream processing using OpenCV
            cap = cv2.VideoCapture(video_path)
            frame_count = 0

            while cap.isOpened():
                ret, frame = cap.read()
                if not ret:
                    break

                unique_frame_name = f"{seq}_frame_{frame_count:04d}"
                
                # Directly map paths to target allocation split folders
                img_dest_path = os.path.join(OUTPUT_ROOT, split_name, "images", f"{unique_frame_name}.png")
                lbl_dest_path = os.path.join(OUTPUT_ROOT, split_name, "labels", f"{unique_frame_name}.txt")

                # Save raw PNG frame
                cv2.imwrite(img_dest_path, frame)

                # Process YOLO annotation parameters
                yolo_lines = []
                if frame_count in frame_annotations:
                    for obj in frame_annotations[frame_count]:
                        cx = float(obj['x'])
                        cy = float(obj['y'])
                        w = float(obj['width'])
                        h = float(obj['height'])

                        # Scale coordinates natively between 0 and 1
                        cx_norm = cx / IMG_SIZE
                        cy_norm = cy / IMG_SIZE
                        w_norm = w / IMG_SIZE
                        h_norm = h / IMG_SIZE

                        yolo_lines.append(f"0 {cx_norm:.6f} {cy_norm:.6f} {w_norm:.6f} {h_norm:.6f}")

                # Save standard label layout
                with open(lbl_dest_path, "w") as lf:
                    lf.write("\n".join(yolo_lines))

                frame_count += 1
            cap.release()


# =========================
# Step 3: Autogenerate dataset.yaml
# =========================
def generate_yaml_config():
    yaml_path = os.path.join(OUTPUT_ROOT, "dataset.yaml")
    
    yaml_content = f"""# Autogenerated Space Debris YOLO Dataset Configuration File
path: {os.path.abspath(OUTPUT_ROOT)}
train: train/images
val: val/images
test: test/images

names:
  0: debris
"""
    with open(yaml_path, "w") as f:
        f.write(yaml_content.strip())
    print(f"📝 Generated YOLO config profile at: {yaml_path}")


# =========================
# Main Runner Method
# =========================
def main():
    # Recommended fix: Nuke any existing old directory structures completely
    if os.path.exists(OUTPUT_ROOT):
        print(f"🧹 Found existing dataset at '{OUTPUT_ROOT}'. Purging old runs...")
        shutil.rmtree(OUTPUT_ROOT)

    # Recreate the directory architecture completely blank
    for split in ["train", "val", "test"]:
        os.makedirs(os.path.join(OUTPUT_ROOT, split, "images"), exist_ok=True)
        os.makedirs(os.path.join(OUTPUT_ROOT, split, "labels"), exist_ok=True)

    # Execute core pipeline modules
    video_splits = get_video_splits()
    process_and_build(video_splits)
    generate_yaml_config()
    
    # Another quick check: Quick data validation count assertion check
    print("\n📊 Verification - Dataset File Inventory Counts:")
    for split in ["train", "val", "test"]:
        img_count = len(os.listdir(os.path.join(OUTPUT_ROOT, split, "images")))
        lbl_count = len(os.listdir(os.path.join(OUTPUT_ROOT, split, "labels")))
        print(f" ├─ {split.capitalize():<5} -> Images: {img_count:<5} | Labels: {lbl_count:<5}")

    print(f"\n🎉 Clean, leak-free dataset rebuilt from scratch successfully!")


if __name__ == "__main__":
    main()
